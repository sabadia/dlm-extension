// Generates src/lib/api/schema.d.ts from the pinned OpenAPI document (spec/openapi-3.0.json).
// `node tools/generate-api.mjs` writes it; `--check` fails when the committed file is out of date.
import { createHash } from 'node:crypto';
import { readFileSync, writeFileSync } from 'node:fs';
import openapiTS, { astToString } from 'openapi-typescript';

const SPEC = new URL('../spec/openapi-3.0.json', import.meta.url);
const OUT = new URL('../src/lib/api/schema.d.ts', import.meta.url);

const sha = createHash('sha256').update(readFileSync(SPEC)).digest('hex');
const ast = await openapiTS(SPEC);
const text = `// GENERATED by tools/generate-api.mjs from spec/openapi-3.0.json. Do not edit.\n// spec-sha256: ${sha}\n\n${astToString(ast)}`;

if (process.argv.includes('--check')) {
  let current = '';
  try {
    current = readFileSync(OUT, 'utf8');
  } catch {
    // missing: reported below
  }
  if (current !== text) {
    console.error('src/lib/api/schema.d.ts is out of date: run `pnpm generate:api`.');
    process.exit(1);
  }
  console.log('api schema: ok');
} else {
  writeFileSync(OUT, text);
  console.log('wrote src/lib/api/schema.d.ts');
}
